using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using Shiny.AppDeviceBridge.Client;

namespace Shiny.AppDeviceBridge.TypeScript;

/// <summary>
/// The TypeScript half of the typed clients: one module per bridge client assembly, holding its contracts and a client
/// class, generated from the same [BridgeClient] interface the C# client is. Parameters are classified exactly as the
/// C# generator classifies them — route token, then body, then query — so the two clients send identical requests.
/// </summary>
public static partial class TypeScriptGenerator
{
    const string SharedAssembly = "Shiny.AppDeviceBridge.Client";
    const string Header = "// <auto-generated/>\n// Generated by tools/Shiny.AppDeviceBridge.TypeScript from {0}. Do not edit; run the tool instead.\n";

    /// <summary>File name → content, for every generated module and the index.</summary>
    public static IReadOnlyDictionary<string, string> Generate()
    {
        var assemblies = LoadClientAssemblies();
        var modules = new SortedDictionary<string, Module>(StringComparer.Ordinal);

        Module ModuleFor(Assembly assembly)
        {
            var name = ModuleName(assembly);
            if (!modules.TryGetValue(name, out var module))
                modules[name] = module = new Module(name, assembly);

            return module;
        }

        // The shared package first: it declares the built-in bridges, and every other module imports from it.
        foreach (var assembly in assemblies.Prepend(typeof(BridgeClientAttribute).Assembly))
        {
            foreach (var bridge in assembly.GetExportedTypes().Where(x => x.IsInterface && x.GetCustomAttribute<BridgeClientAttribute>() is not null))
            {
                var module = ModuleFor(assembly);
                module.Bridges.Add(bridge);
                Walk(bridge, ModuleFor);
            }
        }

        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var module in modules.Values)
            files[module.Name + ".ts"] = Emit(module, modules);

        files["index.ts"] = EmitIndex(modules.Values);
        return files;
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Discovery
    // ---------------------------------------------------------------------------------------------------------------

    static List<Assembly> LoadClientAssemblies()
        => [.. Directory.EnumerateFiles(AppContext.BaseDirectory, "Shiny.AppDeviceBridge.*.Client.dll")
            .Select(path => Assembly.Load(AssemblyName.GetAssemblyName(path)))
            .OrderBy(x => x.GetName().Name, StringComparer.Ordinal)];

    static string ModuleName(Assembly assembly)
    {
        var name = assembly.GetName().Name!;
        if (name == SharedAssembly)
            return "shared";

        var bridge = name["Shiny.AppDeviceBridge.".Length..^".Client".Length];
        return Kebab(bridge);
    }

    /// <summary>Records which declared types each module needs, and whether each is read, written, or both.</summary>
    static void Walk(Type bridge, Func<Assembly, Module> moduleFor)
    {
        foreach (var method in bridge.GetMethods())
        {
            if (method.GetCustomAttribute<BridgeEventAttribute>() is not null)
            {
                Collect(method.GetParameters()[0].ParameterType.GetGenericArguments()[0], Usage.Output, moduleFor);
                continue;
            }

            if (Result(method) is { } result)
                Collect(result, Usage.Output, moduleFor);

            var route = method.GetCustomAttribute<BridgeRouteAttribute>()!;
            foreach (var parameter in method.GetParameters())
            {
                var kind = Classify(parameter, route);
                Collect(parameter.ParameterType, kind == ParameterKind.Body ? Usage.Input : Usage.Output, moduleFor);
            }
        }
    }

    static void Collect(Type type, Usage usage, Func<Assembly, Module> moduleFor)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;

        if (ElementType(type) is { } element)
        {
            Collect(element, usage, moduleFor);
            return;
        }

        if (!IsDeclared(type))
            return;

        var module = moduleFor(type.Assembly);
        if (module.Types.TryGetValue(type, out var existing))
        {
            // Read anywhere means every member is always present; that wins over the looser shape a request allows.
            if (existing == Usage.Output || usage == Usage.Input)
                return;

            module.Types[type] = Usage.Output;
            return;
        }

        module.Types[type] = usage;

        if (type.IsEnum)
            return;

        foreach (var property in Properties(type))
            Collect(property.PropertyType, usage, moduleFor);
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Emission
    // ---------------------------------------------------------------------------------------------------------------

    static string Emit(Module module, IReadOnlyDictionary<string, Module> modules)
    {
        var docs = XmlDocs.For(module.Assembly);
        var body = new StringBuilder();
        var imports = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);

        string Ref(Type type)
        {
            var owner = ModuleName(type.Assembly);
            if (owner != module.Name)
            {
                if (!imports.TryGetValue(owner, out var names))
                    imports[owner] = names = new SortedSet<string>(StringComparer.Ordinal);

                names.Add(type.Name);
            }

            return type.Name;
        }

        foreach (var (type, usage) in module.Types.OrderBy(x => x.Key.Name, StringComparer.Ordinal))
        {
            body.AppendLine();
            WriteDoc(body, docs.Type(type), "");

            if (type.IsEnum)
            {
                body.AppendLine($"export type {type.Name} = {String.Join(" | ", Enum.GetNames(type).Select(x => $"\"{x}\""))};");
                continue;
            }

            body.AppendLine($"export interface {type.Name} {{");
            foreach (var property in Properties(type))
            {
                WriteDoc(body, docs.Property(property), "    ");

                var nullable = IsNullable(property);
                var optional = usage == Usage.Input && !IsRequired(property);
                var tsType = TsType(property.PropertyType, Ref, forParameter: usage == Usage.Input) + (nullable ? " | null" : "");

                body.AppendLine($"    {JsonName(property)}{(optional ? "?" : "")}: {tsType};");
            }

            body.AppendLine("}");
        }

        foreach (var bridge in module.Bridges.OrderBy(x => x.Name, StringComparer.Ordinal))
            WriteClient(body, bridge, docs, Ref);

        var text = new StringBuilder();
        text.AppendFormat(Header, module.Assembly.GetName().Name);

        if (module.Bridges.Count > 0)
        {
            var generated = body.ToString();
            var helpers = new[] { "browserTransport", "call", "callBlob", "callVoid", "dateText", "query", "segment" }
                .Where(helper => Regex.IsMatch(generated, $@"\b{helper}(<|\()"));

            text.AppendLine($"import {{ type BridgeTransport, {String.Join(", ", helpers)} }} from \"./core\";");
        }

        foreach (var (from, names) in imports)
            text.AppendLine($"import type {{ {String.Join(", ", names)} }} from \"./{from}\";");

        text.Append(body);
        return text.ToString();
    }

    static void WriteClient(StringBuilder body, Type bridge, XmlDocs docs, Func<Type, string> reference)
    {
        var attribute = bridge.GetCustomAttribute<BridgeClientAttribute>()!;
        var className = bridge.Name.Length > 1 && bridge.Name[0] == 'I' && Char.IsUpper(bridge.Name[1]) ? bridge.Name[1..] : bridge.Name;

        body.AppendLine();
        WriteDoc(body, docs.Type(bridge), "");
        body.AppendLine($"export class {className} {{");
        body.AppendLine("    constructor(private readonly transport: BridgeTransport = browserTransport()) {}");

        foreach (var method in bridge.GetMethods().OrderBy(x => x.MetadataToken))
        {
            body.AppendLine();
            WriteDoc(body, docs.Method(method), "    ");

            if (method.GetCustomAttribute<BridgeEventAttribute>() is { } @event)
            {
                var payload = reference(method.GetParameters()[0].ParameterType.GetGenericArguments()[0]);
                body.AppendLine($"    {MemberName(method)}(handler: (payload: {payload}) => void): () => void {{");
                body.AppendLine($"        return this.transport.subscribe(\"{@event.EventName}\", json => handler(JSON.parse(json) as {payload}));");
                body.AppendLine("    }");
                continue;
            }

            var route = method.GetCustomAttribute<BridgeRouteAttribute>()!;
            var parameters = method.GetParameters();
            var signature = new List<string>();
            var options = new List<string>();
            var queryParts = new List<string>();
            string? content = null;
            var path = attribute.Name.Trim('/') + (route.Pattern.Trim('/') is { Length: > 0 } p ? "/" + p : "");
            var hasSignal = false;

            // The trailing bag of optional arguments is "options" unless a parameter already has that name.
            var bag = parameters.Any(x => x.Name == "options") ? "requestOptions" : "options";

            foreach (var parameter in parameters)
            {
                var kind = Classify(parameter, route);
                var name = parameter.Name!;
                var optional = parameter.HasDefaultValue && kind != ParameterKind.Cancellation;
                var access = optional ? $"{bag}?.{name}" : name;

                switch (kind)
                {
                    case ParameterKind.Cancellation:
                        hasSignal = true;
                        continue;

                    case ParameterKind.Route:
                        path = path.Replace("{" + name + "}", "${segment(" + access + ")}");
                        break;

                    case ParameterKind.Query:
                        var queryName = parameter.GetCustomAttribute<BridgeQueryAttribute>()?.Name ?? name;
                        queryParts.Add($"{Quote(queryName)}: {(IsDate(parameter.ParameterType) ? $"dateText({access})" : access)}");
                        break;

                    case ParameterKind.Body:
                        var raw = parameter.GetCustomAttribute<BridgeBodyAttribute>();
                        content = IsRawBody(parameter.ParameterType)
                            ? $"body: {access}, contentType: \"{(raw is { ContentType: not "application/json" } ? raw.ContentType : "application/octet-stream")}\""
                            : $"json: {access}";
                        break;
                }

                var tsType = TsType(parameter.ParameterType, reference, forParameter: true)
                             + (IsNullable(parameter) ? " | null" : "");

                if (optional)
                    options.Add($"{name}?: {tsType}");
                else
                    signature.Add($"{name}: {tsType}");
            }

            if (hasSignal)
                options.Add("signal?: AbortSignal");

            if (options.Count > 0)
                signature.Add($"{bag}?: {{ {String.Join("; ", options)} }}");

            var target = "`" + path + "`" + (queryParts.Count > 0 ? $" + query({{ {String.Join(", ", queryParts)} }})" : "");
            var init = String.Join(", ", new[] { content, hasSignal ? $"signal: {bag}?.signal" : null }.Where(x => x is not null));
            var initText = init.Length > 0 ? $", {{ {init} }}" : "";
            var result = Result(method);

            var (returns, invocation) = result switch
            {
                null => ("Promise<void>", $"callVoid(this.transport, \"{route.Method}\", {target}{initText})"),
                _ when result == typeof(Stream) || result == typeof(byte[]) => ("Promise<Blob>", $"callBlob(this.transport, \"{route.Method}\", {target}{initText})"),
                _ => (TsType(result, reference, forParameter: false) + (IsNullableResult(method) ? " | null" : "")) is var resultType
                    ? ($"Promise<{resultType}>", $"call<{resultType}>(this.transport, \"{route.Method}\", {target}{initText})")
                    : default
            };

            body.AppendLine($"    {MemberName(method)}({String.Join(", ", signature)}): {returns} {{");
            body.AppendLine($"        return {invocation};");
            body.AppendLine("    }");
        }

        body.AppendLine("}");
    }

    static string EmitIndex(IEnumerable<Module> modules)
    {
        // One flat namespace for the page: a name declared twice would silently shadow, so it fails the build instead.
        var seen = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var module in modules)
        {
            foreach (var name in module.Types.Keys.Select(x => x.Name).Concat(module.Bridges.Select(x => x.Name[1..])))
            {
                if (seen.TryGetValue(name, out var other) && other != module.Name)
                    throw new InvalidOperationException($"'{name}' is declared by both the {other} and {module.Name} clients. Rename one of the contracts.");

                seen[name] = module.Name;
            }
        }

        var text = new StringBuilder();
        text.AppendFormat(Header, "every bridge client");
        text.AppendLine("export * from \"./core\";");
        foreach (var module in modules)
            text.AppendLine($"export * from \"./{module.Name}\";");

        return text.ToString();
    }

