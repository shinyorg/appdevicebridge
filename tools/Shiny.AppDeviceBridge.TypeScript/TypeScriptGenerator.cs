    static string TsType(Type type, Func<Type, string> reference, bool forParameter)
    {
        if (Nullable.GetUnderlyingType(type) is { } underlying)
            return TsType(underlying, reference, forParameter) + " | null";

        if (type == typeof(string) || type == typeof(char) || type == typeof(Guid) || type == typeof(TimeSpan)
            || type == typeof(Uri) || type == typeof(DateOnly) || type == typeof(TimeOnly))
            return "string";

        if (type == typeof(DateTime) || type == typeof(DateTimeOffset))
            return forParameter ? "Date | string" : "string";

        if (type == typeof(bool))
            return "boolean";

        if (type.IsPrimitive || type == typeof(decimal))
            return "number";

        if (type == typeof(byte[]))
            return forParameter ? "Blob | ArrayBuffer | Uint8Array" : "string";

        if (type == typeof(Stream))
            return "Blob | ArrayBuffer | Uint8Array";

        if (type == typeof(object) || type == typeof(JsonElement))
            return "unknown";

        if (DictionaryValue(type) is { } value)
            return $"Record<string, {TsType(value, reference, forParameter)}>";

        if (ElementType(type) is { } element)
        {
            var inner = TsType(element, reference, forParameter);
            return inner.Contains(' ') ? $"({inner})[]" : inner + "[]";
        }

        if (IsDeclared(type))
            return reference(type);

        // A framework enum such as DayOfWeek: its names, inline, since there is no contract module to declare it in.
        if (type.IsEnum)
            return "(" + String.Join(" | ", Enum.GetNames(type).Select(x => $"\"{x}\"")) + ")";

        throw new NotSupportedException($"{type} has no TypeScript mapping. Add one to TypeScriptGenerator.TsType.");
    }

    /// <summary>A contract type — declared in a bridge's own assembly — rather than a framework type the mapping covers.</summary>
    static bool IsDeclared(Type type)
        => type.Assembly.GetName().Name!.StartsWith("Shiny.AppDeviceBridge", StringComparison.Ordinal)
           && (type.IsEnum || type.IsClass || (type.IsValueType && !type.IsPrimitive));

    static bool IsDate(Type type) => (Nullable.GetUnderlyingType(type) ?? type) is var t && (t == typeof(DateTime) || t == typeof(DateTimeOffset));

    static bool IsRawBody(Type type) => type == typeof(Stream) || type == typeof(byte[]) || type == typeof(string);

    static Type? ElementType(Type type)
    {
        if (type == typeof(string) || type == typeof(byte[]))
            return null;

        if (type.IsArray)
            return type.GetElementType();

        if (DictionaryValue(type) is not null)
            return null;

        return type.IsGenericType && type.GetInterfaces().Append(type).Any(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IEnumerable<>))
            ? type.GetGenericArguments()[0]
            : null;
    }

    static Type? DictionaryValue(Type type)
        => type.GetInterfaces().Append(type)
            .FirstOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>) && i.GetGenericArguments()[0] == typeof(string))
            ?.GetGenericArguments()[1];

    static IEnumerable<PropertyInfo> Properties(Type type)
        => type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(x => x.GetIndexParameters().Length == 0 && x.GetCustomAttribute<JsonIgnoreAttribute>() is null)
            .OrderBy(x => x.MetadataToken);

    static string JsonName(PropertyInfo property)
        => property.GetCustomAttribute<JsonPropertyNameAttribute>()?.Name ?? JsonNamingPolicy.CamelCase.ConvertName(property.Name);

    /// <summary>
    /// A <c>required</c> member, or a positional record parameter with no default — either way the host cannot read the
    /// request without it.
    /// </summary>
    static bool IsRequired(PropertyInfo property)
        => property.GetCustomAttribute<RequiredMemberAttribute>() is not null
           || property.DeclaringType!.GetConstructors().Any(c => c.GetParameters().Any(p =>
               String.Equals(p.Name, property.Name, StringComparison.Ordinal) && !p.HasDefaultValue));

    /// <summary>A <c>Task&lt;T?&gt;</c> for a reference type: the call answers null when there is nothing.</summary>
    static bool IsNullableResult(MethodInfo method)
        => Result(method) is { IsValueType: false }
           && new NullabilityInfoContext().Create(method.ReturnParameter).GenericTypeArguments[0].ReadState == NullabilityState.Nullable;

    static bool IsNullable(PropertyInfo property)
        => !property.PropertyType.IsValueType && new NullabilityInfoContext().Create(property).ReadState == NullabilityState.Nullable;

    static bool IsNullable(ParameterInfo parameter)
        => !parameter.ParameterType.IsValueType && new NullabilityInfoContext().Create(parameter).WriteState == NullabilityState.Nullable;

    static Type? Result(MethodInfo method)
        => method.ReturnType.IsGenericType && method.ReturnType.GetGenericTypeDefinition() == typeof(Task<>)
            ? method.ReturnType.GetGenericArguments()[0]
            : null;

    static ParameterKind Classify(ParameterInfo parameter, BridgeRouteAttribute route)
    {
        if (parameter.ParameterType == typeof(CancellationToken))
            return ParameterKind.Cancellation;

        if (route.Pattern.Contains("{" + parameter.Name + "}", StringComparison.Ordinal))
            return ParameterKind.Route;

        var simple = IsSimple(parameter.ParameterType);
        if (parameter.GetCustomAttribute<BridgeBodyAttribute>() is not null || (!simple && route.Method is "POST" or "PUT"))
            return ParameterKind.Body;

        return ParameterKind.Query;
    }

    static bool IsSimple(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        return type.IsEnum || type.IsPrimitive || type == typeof(string) || type == typeof(decimal) || type == typeof(DateTime)
               || type == typeof(DateTimeOffset) || type == typeof(Guid) || type == typeof(TimeSpan);
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Text
    // ---------------------------------------------------------------------------------------------------------------

    static void WriteDoc(StringBuilder body, string? doc, string indent)
    {
        if (String.IsNullOrWhiteSpace(doc))
            return;

        var lines = doc.Split('\n');
        if (lines.Length == 1)
        {
            body.AppendLine($"{indent}/** {lines[0]} */");
            return;
        }

        body.AppendLine($"{indent}/**");
        foreach (var line in lines)
            body.AppendLine(line.Length == 0 ? $"{indent} *" : $"{indent} * {line}");
        body.AppendLine($"{indent} */");
    }

    static string MemberName(MethodInfo method)
    {
        var name = method.Name.EndsWith("Async", StringComparison.Ordinal) ? method.Name[..^"Async".Length] : method.Name;
        return JsonNamingPolicy.CamelCase.ConvertName(name);
    }

    static string Quote(string name) => KebabOrIdentifier().IsMatch(name) ? name : $"\"{name}\"";

    static string Kebab(string pascal) => PascalBoundary().Replace(pascal, "$1-$2").ToLowerInvariant();

    [GeneratedRegex("^[A-Za-z_$][A-Za-z0-9_$]*$")]
    private static partial Regex KebabOrIdentifier();

    [GeneratedRegex("([a-z0-9])([A-Z])")]
    private static partial Regex PascalBoundary();

    enum Usage { Input, Output }

    enum ParameterKind { Cancellation, Route, Query, Body }

    sealed class Module(string name, Assembly assembly)
    {
        public string Name { get; } = name;

        public Assembly Assembly { get; } = assembly;

        public Dictionary<Type, Usage> Types { get; } = [];

        public List<Type> Bridges { get; } = [];
    }
}
